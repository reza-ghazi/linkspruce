// Node-side performance of core algorithms on the synthetic 25k library.
import { generateLibrary } from '../tests/fixtures/synthetic-library.ts';
import { FakeBookmarks, FakeStore, ManualClock } from '../tests/helpers/fake-chrome.ts';
import { inventory, offlineDraft } from '../src/core/discovery/discovery.ts';
import { RulesClassifier, type Assignment } from '../src/core/classify/classifier.ts';
import { findDuplicates } from '../src/core/duplicates.ts';
import { freeze } from '../src/core/taxonomy/taxonomy.ts';
import { flattenTree } from '../src/core/tree.ts';
import { buildOrganizePlan, planToSteps } from '../src/core/plan.ts';
import { Journal } from '../src/core/journal.ts';
import { SnapshotStore } from '../src/core/backup.ts';

const n = Number(process.argv[2] ?? 25000);
const lib = generateLibrary(n);
const bm = new FakeBookmarks();
const t = (label: string, t0: number) => console.log(`${label.padEnd(34)} ${Math.round(performance.now() - t0)} ms`);
let t0 = performance.now();
const cache = new Map<string, string>();
for (const it of lib) {
  const key = it.path.join('/');
  let parent = cache.get(key);
  if (!parent) cache.set(key, (parent = await bm.ensurePath(it.path)));
  await bm.create({ parentId: parent, title: it.title, url: it.url });
}
t(`seed ${n} bookmarks (fake API)`, t0);
const [root] = await bm.getTree();
t0 = performance.now();
const flat = flattenTree(root!);
t('flatten tree', t0);
const items = flat.bookmarks.map((b) => ({ id: b.id, title: b.title, url: b.url, folderPath: b.path }));
t0 = performance.now();
const inv = inventory(items);
t('inventory', t0);
t0 = performance.now();
const tax = freeze(offlineDraft(inv, 't', 0).taxonomy, 0);
t('offline draft', t0);
t0 = performance.now();
const clf = new RulesClassifier(tax);
const as = new Map<string, Assignment>();
for (const it of items) as.set(it.id, clf.classify(it, 0));
t('classify all (offline rules)', t0);
t0 = performance.now();
const d = findDuplicates(flat.bookmarks);
t(`duplicates (${d.groups.length} groups)`, t0);
t0 = performance.now();
const plan = buildOrganizePlan({ tree: root!, flat, taxonomy: tax, assignments: as, folderMap: new Map(), now: 0, id: 'p', settings: { destinationRootId: '2', rootFolderName: 'LinkSpruce', includeBands: ['high', 'medium'], scopeFolderIds: [], protectedFolderIds: [], skipAlreadyOrganized: true } });
t(`plan (${plan.moves.length} moves)`, t0);
const store = new FakeStore();
t0 = performance.now();
const snap = await new SnapshotStore(store, new ManualClock()).capture(bm, 'perf');
t(`verified snapshot (${(snap.bytes / 1048576).toFixed(1)} MB)`, t0);
t0 = performance.now();
const j = new Journal(store, bm, new ManualClock());
const h = await j.run((await j.begin('organize', 'perf', planToSteps(plan), { source: 'user' })).id);
t(`journaled apply (${h.counts.done} steps)`, t0);
console.log(`storage writes: ${store.setCount}, stored bytes: ${(store.bytes() / 1048576).toFixed(1)} MB, heap: ${Math.round(process.memoryUsage().heapUsed / 1048576)} MB`);
t0 = performance.now();
const u = await j.undo(h.id);
t(`undo (${u.counts.done} steps, ${u.status})`, t0);
